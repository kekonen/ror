//! Rorschach ZK Image Verification - Solana Program
//!
//! This program verifies Groth16 proofs of Rorschach image generation
//! using Solana's native groth16::verify() syscall.

use borsh::{BorshDeserialize, BorshSerialize};
use solana_program::{
    account_info::{next_account_info, AccountInfo},
    entrypoint,
    entrypoint::ProgramResult,
    msg,
    program_error::ProgramError,
    pubkey::Pubkey,
    sysvar::{instructions::ID as IX_ID, Sysvar},
};

#[cfg(not(feature = "no-entrypoint"))]
entrypoint!(process_instruction);

/// Program state enum
#[derive(BorshSerialize, BorshDeserialize, Debug)]
pub enum RorschachInstruction {
    /// Verify a Groth16 proof of Rorschach image generation
    ///
    /// Accounts expected:
    /// 0. `[writable]` Proof verification record (PDA)
    /// 1. `[signer]` User wallet
    /// 2. `[]` Verifying key account
    /// 3. `[]` System program
    /// 4. `[]` Instructions sysvar (for Groth16 verify)
    VerifyProof {
        /// Groth16 proof bytes (generated by bb or snarkjs)
        proof: Vec<u8>,
        /// Public inputs (image hash, etc.)
        public_inputs: Vec<u8>,
    },

    /// Initialize verifying key account
    ///
    /// Accounts expected:
    /// 0. `[writable]` Verifying key account
    /// 1. `[signer]` Authority (deployer)
    /// 2. `[]` System program
    InitializeVerifyingKey {
        /// Groth16 verifying key bytes
        verifying_key: Vec<u8>,
    },
}

/// Verification record stored on-chain
#[derive(BorshSerialize, BorshDeserialize, Debug)]
pub struct VerificationRecord {
    /// User who submitted the proof
    pub user: Pubkey,
    /// Block timestamp when verified
    pub timestamp: i64,
    /// Hash of the public inputs (for indexing)
    pub public_inputs_hash: [u8; 32],
    /// Proof was verified successfully
    pub verified: bool,
}

/// Verifying key account data
#[derive(BorshSerialize, BorshDeserialize, Debug)]
pub struct VerifyingKey {
    /// Authority that can update the key
    pub authority: Pubkey,
    /// Groth16 verifying key data
    pub key_data: Vec<u8>,
}

/// Program entrypoint
pub fn process_instruction(
    program_id: &Pubkey,
    accounts: &[AccountInfo],
    instruction_data: &[u8],
) -> ProgramResult {
    let instruction = RorschachInstruction::try_from_slice(instruction_data)
        .map_err(|_| ProgramError::InvalidInstructionData)?;

    match instruction {
        RorschachInstruction::VerifyProof {
            proof,
            public_inputs,
        } => {
            msg!("Instruction: VerifyProof");
            process_verify_proof(program_id, accounts, proof, public_inputs)
        }
        RorschachInstruction::InitializeVerifyingKey { verifying_key } => {
            msg!("Instruction: InitializeVerifyingKey");
            process_initialize_verifying_key(program_id, accounts, verifying_key)
        }
    }
}

/// Process VerifyProof instruction
fn process_verify_proof(
    program_id: &Pubkey,
    accounts: &[AccountInfo],
    proof: Vec<u8>,
    public_inputs: Vec<u8>,
) -> ProgramResult {
    let account_info_iter = &mut accounts.iter();

    let verification_record_account = next_account_info(account_info_iter)?;
    let user_account = next_account_info(account_info_iter)?;
    let verifying_key_account = next_account_info(account_info_iter)?;
    let _system_program = next_account_info(account_info_iter)?;
    let instructions_sysvar = next_account_info(account_info_iter)?;

    // Verify user signed the transaction
    if !user_account.is_signer {
        msg!("User must sign the transaction");
        return Err(ProgramError::MissingRequiredSignature);
    }

    // Check instructions sysvar is correct
    if instructions_sysvar.key != &IX_ID {
        msg!("Instructions sysvar must be provided");
        return Err(ProgramError::IncorrectProgramId);
    }

    // Load verifying key
    let vk_data = VerifyingKey::try_from_slice(&verifying_key_account.data.borrow())
        .map_err(|_| ProgramError::InvalidAccountData)?;

    msg!("Verifying Groth16 proof...");
    msg!("Proof size: {} bytes", proof.len());
    msg!("Public inputs size: {} bytes", public_inputs.len());
    msg!("Verifying key size: {} bytes", vk_data.key_data.len());

    // CRITICAL: Use Solana's native Groth16 verification syscall
    // This is why Solana is perfect - built-in support!
    use solana_program::alt_bn128::prelude::*;

    // The actual verification happens here via syscall
    // Format: alt_bn128_groth16_verify(proof, public_inputs, vk) -> bool
    let is_valid = verify_groth16_proof(&proof, &public_inputs, &vk_data.key_data)?;

    if !is_valid {
        msg!("Proof verification FAILED");
        return Err(ProgramError::InvalidArgument);
    }

    msg!("Proof verification SUCCEEDED ✓");

    // Calculate public inputs hash for indexing
    use solana_program::hash::hash;
    let public_inputs_hash = hash(&public_inputs).to_bytes();

    // Get current timestamp
    let clock = solana_program::clock::Clock::get()?;

    // Create verification record
    let record = VerificationRecord {
        user: *user_account.key,
        timestamp: clock.unix_timestamp,
        public_inputs_hash,
        verified: true,
    };

    // Serialize and store
    let mut record_data = verification_record_account.data.borrow_mut();
    record.serialize(&mut &mut record_data[..])?;

    msg!("Verification record saved");
    msg!("User: {}", user_account.key);
    msg!("Timestamp: {}", clock.unix_timestamp);

    Ok(())
}

/// Process InitializeVerifyingKey instruction
fn process_initialize_verifying_key(
    _program_id: &Pubkey,
    accounts: &[AccountInfo],
    verifying_key: Vec<u8>,
) -> ProgramResult {
    let account_info_iter = &mut accounts.iter();

    let vk_account = next_account_info(account_info_iter)?;
    let authority_account = next_account_info(account_info_iter)?;
    let _system_program = next_account_info(account_info_iter)?;

    // Verify authority signed
    if !authority_account.is_signer {
        msg!("Authority must sign");
        return Err(ProgramError::MissingRequiredSignature);
    }

    msg!("Initializing verifying key account");
    msg!("Verifying key size: {} bytes", verifying_key.len());

    // Create verifying key data
    let vk_data = VerifyingKey {
        authority: *authority_account.key,
        key_data: verifying_key,
    };

    // Serialize and store
    let mut vk_account_data = vk_account.data.borrow_mut();
    vk_data.serialize(&mut &mut vk_account_data[..])?;

    msg!("Verifying key initialized");

    Ok(())
}

