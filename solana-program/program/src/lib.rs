#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_verification_record_serialization() {
        let record = VerificationRecord {
            user: Pubkey::new_unique(),
            timestamp: 1234567890,
            public_inputs_hash: [0u8; 32],
            verified: true,
        };

        let serialized = record.try_to_vec().unwrap();
        let deserialized = VerificationRecord::try_from_slice(&serialized).unwrap();

        assert_eq!(record.user, deserialized.user);
        assert_eq!(record.timestamp, deserialized.timestamp);
        assert_eq!(record.verified, deserialized.verified);
    }
}
